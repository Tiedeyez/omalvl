SIZE = 12


def check():
    """Every icon is 12x12 and uses only the five slot characters."""
    bad = []
    for name, rows in ICONS.items():
        if len(rows) != SIZE or any(len(r) != SIZE or set(r) - set(" #ab.") for r in rows):
            bad.append(name)
    return bad


def svg(name, px=4, ink="currentColor", tint="#7aa2f7", accent="#e0af68", shade_alpha=0.35):
    """One icon as a crisp SVG (one rect per run of same-colour pixels in a row)."""
    fill = {"#": ink, "a": tint, "b": accent, ".": ink}
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" '
           'shape-rendering="crispEdges">' % (SIZE * px, SIZE * px, SIZE, SIZE)]
    for y, row in enumerate(ICONS[name]):
        x = 0
        while x < SIZE:
            c = row[x]
            run = 1
            while x + run < SIZE and row[x + run] == c:
                run += 1
            if c != " ":
                op = ' fill-opacity="%s"' % shade_alpha if c == "." else ""
                out.append('<rect x="%d" y="%d" width="%d" height="1" fill="%s"%s/>' % (x, y, run, fill[c], op))
            x += run
    out.append("</svg>")
    return "".join(out)
